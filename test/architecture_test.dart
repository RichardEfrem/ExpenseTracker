void main() {
  group('architecture of this project', () {
    final project = Project.fromDisk();
    for (final MapEntry(key: name, value: rule) in rules.entries) {
      test(name, () {
        final violations = rule(project);
        expect(violations, isEmpty, reason: violations.join('\n'));
      });
    }
  });

  group('rules catch violations', () {
    const pkg = 'package:$_package';

    /// A small compliant tree: single-slice module `categories`, sliced
    /// module `reports` with a `shared` slice, and a module `home` that uses
    /// both through their public APIs.
    Map<String, String> validTree() => {
      'lib/main.dart': "import '$pkg/app.dart';",
      'lib/app.dart':
          "import '$pkg/core/router/app_router.dart';\n"
          "import '$pkg/features/categories/categories_presentation.dart';",
      'lib/core/router/app_router.dart':
          "import '$pkg/features/home/home_routes.dart';",
      'lib/core/error/failure.dart': '',
      for (final m in ['categories', 'reports', 'home'])
        for (final kind in _apiKinds) 'lib/features/$m/${m}_$kind.dart': '',
      'lib/features/categories/categories_domain.dart':
          "export '$pkg/features/categories/domain/entities/category.dart' show Category;",
      'lib/features/categories/categories_presentation.dart':
          "export '$pkg/features/categories/domain/entities/category.dart' show Category;\n"
          "export '$pkg/features/categories/presentation/widgets/category_grid.dart'\n"
          '    show CategoryGrid, CategoryCell;',
      'lib/features/categories/domain/entities/category.dart':
          "import '$pkg/core/error/failure.dart';",
      'lib/features/categories/data/categories_providers.dart':
          "import '$pkg/features/categories/data/repositories/category_repository_impl.dart';",
      'lib/features/categories/data/repositories/category_repository_impl.dart':
          "import '$pkg/features/categories/domain/entities/category.dart';",
      'lib/features/categories/presentation/widgets/category_grid.dart':
          "import 'package:flutter/material.dart';\n"
          "import '$pkg/features/categories/data/categories_providers.dart';\n"
          "import '$pkg/features/categories/domain/entities/category.dart';",
      'lib/features/reports/shared/domain/entities/report_scope.dart': '',
      'lib/features/reports/statistics/domain/usecases/get_stats.dart':
          "import '$pkg/features/reports/shared/domain/entities/report_scope.dart';\n"
          "import '$pkg/features/categories/categories_domain.dart';",
      'lib/features/reports/statistics/presentation/pages/stats_page.dart':
          "import '$pkg/features/reports/statistics/domain/usecases/get_stats.dart';",
      'lib/features/reports/reports_presentation.dart':
          "export '$pkg/features/reports/statistics/presentation/pages/stats_page.dart' show StatsPage;",
      'lib/features/home/home_routes.dart':
          "import '$pkg/features/home/presentation/pages/home_page.dart';",
      'lib/features/home/presentation/pages/home_page.dart':
          "import '$pkg/features/reports/reports_presentation.dart';\n"
          "import '$pkg/features/categories/categories_presentation.dart';",
      'test/architecture_test.dart': '',
      'test/features/reports/statistics/domain/usecases/get_stats_test.dart':
          "import '$pkg/features/reports/statistics/domain/usecases/get_stats.dart';",
    };

    List<String> run(Map<String, String> changes, {Map<String, String>? base}) {
      final tree = {...(base ?? validTree()), ...changes};
      return [for (final rule in rules.values) ...rule(Project.of(tree))];
    }

    void expectViolation(Map<String, String> changes, String fragment) {
      final violations = run(changes);
      expect(
        violations.any((v) => v.contains(fragment)),
        isTrue,
        reason:
            'expected a violation containing "$fragment", got:\n${violations.join('\n')}',
      );
    }

    test('the valid tree passes every rule', () {
      expect(run(const {}), isEmpty);
    });

    group('placement', () {
      test('file outside core/features', () {
        expectViolation({'lib/utils/x.dart': ''}, 'lib/utils/x.dart');
      });
      test('unknown root file in a module', () {
        expectViolation({'lib/features/home/helpers.dart': ''}, 'module root');
      });
      test('unknown layer subfolder', () {
        expectViolation({
          'lib/features/home/domain/services/x.dart': '',
        }, 'domain/ may only contain');
      });
      test('loose file in presentation/', () {
        expectViolation({
          'lib/features/home/presentation/x.dart': '',
        }, 'files in presentation/');
      });
      test('extra file directly in data/', () {
        expectViolation({
          'lib/features/home/data/helpers.dart': '',
        }, 'only home_providers.dart');
      });
      test('slice without a layer folder', () {
        expectViolation({
          'lib/features/reports/daily/x.dart': '',
        }, 'slice folder');
      });
      test('module mixing layers and slices', () {
        expectViolation({
          'lib/features/home/greeting/domain/entities/g.dart': '',
        }, 'pick one');
      });
      test('module missing a root file', () {
        expectViolation({
          'lib/features/budget/domain/entities/b.dart': '',
        }, 'budget_routes.dart: missing');
      });
      test('generated files follow their source', () {
        expect(
          run({
            'lib/features/home/data/home_providers.g.dart': '',
            'lib/features/home/domain/entities/x.freezed.dart': '',
          }),
          isEmpty,
        );
      });
    });

    group('layers', () {
      test('domain importing Flutter', () {
