// Enforces the architecture rules of CLAUDE.md §1 and §5 by scanning the
// source tree. The rule functions are pure (they take an in-memory
// [Project]), so the second half of this file proves each rule actually
// fails on a violation.
//
// Everything lives in this one file because only `architecture_test.dart`
// may sit at the test root, and tests import each other only by package URI.

