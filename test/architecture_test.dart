typedef Rule = List<String> Function(Project project);

/// Every lib file is in an allowed place; modules are either single-slice or
/// sliced, never both; every module has its four root files.
List<String> placementRule(Project p) {
  final out = <String>[];
  final singleSliced = <String>{};
  final sliced = <String>{};
  final modules = <String>{};
  for (final file in p.lib) {
    try {
      final loc = classify(file.path);
      if (loc.module == null) continue;
      modules.add(loc.module!);
      if (loc.isApi) continue;
      (loc.singleSlice ? singleSliced : sliced).add(loc.module!);
    } on FormatException catch (e) {
      out.add('${file.path}: ${e.message}');
    }
  }
  for (final m in singleSliced.intersection(sliced)) {
    out.add(
      'lib/features/$m: has layers at the module root and slices; pick one',
    );
  }
  for (final m in modules) {
    for (final kind in _apiKinds) {
      final path = 'lib/features/$m/${m}_$kind.dart';
      if (!p.libPaths.contains(path)) {
        out.add('$path: missing module root file');
      }
    }
  }
  return out;
}

/// Layer rules inside a module (CLAUDE §1.1), core and app-root rules.
List<String> layerRule(Project p) {
  const bannedInDomain = [
    'package:flutter/',
    'package:flutter_riverpod/',
    'package:hooks_riverpod/',
    'package:riverpod',
    'package:drift',
    'dart:ui',
  ];
  final out = <String>[];
  for (final file in p.handWritten) {
    final from = _tryClassify(file.path);
    if (from == null) continue;
    for (final d in directivesOf(file.content)) {
      String fail(String why) => '${file.path}: $d — $why';

      if (from.effectiveLayer == 'domain' &&
          bannedInDomain.any(d.uri.startsWith)) {
        out.add(fail('domain must stay pure Dart'));
      }
      final target = d.target;
      if (target == null) continue;
      final to = _tryClassify(target);
      if (to == null) continue;

      if (to.area == Area.appRoot && file.path != 'lib/main.dart') {
        out.add(fail('only main.dart imports app.dart'));
        continue;
      }
      switch (from.area) {
        case Area.core:
          final routerComposesRoutes =
              file.path == _router && to.api == 'routes';
          if (to.area == Area.feature && !routerComposesRoutes) {
            out.add(
              fail(
                'core imports no feature (only the router composes <m>_routes.dart)',
              ),
            );
          }
        case Area.appRoot:
          if (to.area == Area.feature && to.api != 'presentation') {
            out.add(fail('app root may only use <m>_presentation.dart'));
          }
        case Area.feature:
          if (to.area != Area.feature || to.module != from.module) continue;
          if (from.isApi && from.api != 'routes') continue; // publicApiRule
          if (to.isApi) {
            out.add(
              fail(
                'inside a module, import files directly, not the public API',
              ),
            );
            continue;
          }
          final allowed = switch (from.effectiveLayer) {
            'domain' => to.layer == 'domain',
            'data' => to.layer == 'domain' || to.layer == 'data',
            _ =>
              to.layer == 'domain' || to.layer == 'presentation' || to.isWiring,
          };
          if (!allowed) {
            out.add(
              fail(
                '${from.effectiveLayer} may not import ${to.layer}'
                '${from.effectiveLayer == 'presentation' ? ' (only <slice>_providers.dart from data/)' : ''}',
              ),
            );
          }
      }
    }
  }
  return out;
}

/// Modules talk to each other only through the root API file matching the
/// importer's layer; `shared/` is private to its module.
List<String> crossModuleRule(Project p) {
  final out = <String>[];
  for (final file in p.handWritten) {
    final from = _tryClassify(file.path);
    if (from == null || from.area != Area.feature) continue;
    if (from.isApi && from.api != 'routes') continue;
    for (final d in directivesOf(file.content)) {
      final target = d.target;
      if (target == null) continue;
      final to = _tryClassify(target);
      if (to == null || to.area != Area.feature || to.module == from.module) {
        continue;
      }
      final want = from.effectiveLayer!;
      if (to.api != want) {
        out.add(
          '${file.path}: $d — cross-module imports go through '
          '${to.module}_$want.dart${to.isShared ? ' (shared/ is private to its module)' : ''}',
        );
      }
    }
  }
  return out;
}

/// `<m>_{domain,data,presentation}.dart` hold only `export … show …` of their
/// own module, from layers the matching importer could use directly.
List<String> publicApiRule(Project p) {
  final out = <String>[];
  final exportPattern = RegExp(
    r'''^export\s+'([^']+)'\s+show\s+[A-Za-z_$][\w$]*(\s*,\s*[A-Za-z_$][\w$]*)*$''',
  );
  for (final file in p.handWritten) {
    final loc = _tryClassify(file.path);
    if (loc == null || !loc.isApi || loc.api == 'routes') continue;
    final code = file.content
        .replaceAll(RegExp(r'//.*'), '')
        .replaceAll(RegExp(r'/\*[\s\S]*?\*/'), '');
    for (final raw in code.split(';')) {
      final statement = raw.trim().replaceAll(RegExp(r'\s+'), ' ');
      if (statement.isEmpty) continue;
      final match = exportPattern.firstMatch(statement);
      if (match == null) {
        out.add(
          '${file.path}: "$statement" — public API files contain only export … show … lines',
        );
        continue;
      }
      final target = Directive('export', match.group(1)!).target;
      final to = target == null ? null : _tryClassify(target);
      if (to == null || to.module != loc.module || to.isApi) {
        out.add(
          '${file.path}: "$statement" — may only export files of its own module',
        );
        continue;
      }
      final allowed = switch (loc.api) {
        'domain' => to.layer == 'domain',
        'data' => to.layer == 'domain' || to.layer == 'data',
        _ => to.layer == 'domain' || to.layer == 'presentation' || to.isWiring,
      };
      if (!allowed) {
        out.add(
          '${file.path}: "$statement" — ${loc.api} API may not expose ${to.layer}',
        );
      }
    }
  }
  return out;
}

/// Slices within a module and modules among themselves form acyclic graphs;
/// `shared/` imports no sibling slice.
List<String> graphRule(Project p) {
  final out = <String>[];
  final sliceEdges = <String, Set<String>>{};
  final moduleEdges = <String, Set<String>>{};
  for (final file in p.handWritten) {
    final from = _tryClassify(file.path);
    if (from == null || from.area != Area.feature) continue;
    for (final d in directivesOf(file.content)) {
      final target = d.target;
      if (target == null) continue;
      final to = _tryClassify(target);
      if (to == null || to.area != Area.feature) continue;
      if (to.module != from.module) {
        moduleEdges.putIfAbsent(from.module!, () => {}).add(to.module!);
        continue;
      }
      if (from.isApi || to.isApi || from.slice == to.slice) continue;
      if (from.isShared) {
        out.add(
          '${file.path}: $d — shared/ may not import sibling slice ${to.slice}',
        );
      }
      sliceEdges
          .putIfAbsent('${from.module}/${from.slice}', () => {})
          .add('${to.module}/${to.slice}');
    }
  }
  for (final cycle in [..._cycles(sliceEdges), ..._cycles(moduleEdges)]) {
    out.add('import cycle: ${cycle.join(' → ')}');
  }
  return out;
}

/// One representative cycle per strongly-connected back edge.
List<List<String>> _cycles(Map<String, Set<String>> edges) {
  final cycles = <List<String>>[];
  final state = <String, int>{}; // 1 = on stack, 2 = done
  final stack = <String>[];
  void visit(String node) {
    state[node] = 1;
    stack.add(node);
    for (final next in edges[node] ?? const <String>{}) {
      if (state[next] == 1) {
        cycles.add([...stack.sublist(stack.indexOf(next)), next]);
      } else if (state[next] == null) {
        visit(next);
      }
    }
    stack.removeLast();
    state[node] = 2;
  }

  for (final node in edges.keys.toList()..sort()) {
    if (state[node] == null) visit(node);
  }
  return cycles;
}

/// Every import in lib/ and test/ is a `package:` or `dart:` URI.
List<String> packageImportsRule(Project p) {
  // A test can reach a tool-generated helper beside it (drift's migration
  // schemas) only by a relative URI: package: URIs resolve into lib/.
  final generatedTests = {
    for (final f in p.test)
      if (isGeneratedFile(f)) f.path,
  };
  bool isGeneratedSibling(SourceFile from, Directive d) {
    if (!from.path.startsWith('test/')) return false;
    final dir = from.path.substring(0, from.path.lastIndexOf('/'));
    return generatedTests.contains('$dir/${d.uri}');
  }

  return [
    for (final file in [
      ...p.handWritten,
      ...p.test.where((f) => !isGeneratedFile(f)),
    ])
      for (final d in directivesOf(file.content))
        if (d.isRelative && !isGeneratedSibling(file, d))
          '${file.path}: $d — use package:$_package/…',
  ];
}

/// test/ mirrors lib/: only architecture_test.dart at the root, and every
/// other test file's folder exists under lib/.
List<String> testMirrorRule(Project p) {
  final libDirs = {
    for (final path in p.libPaths)
      for (var i = path.indexOf('/'); i != -1; i = path.indexOf('/', i + 1))
        path.substring(0, i),
  };
  final out = <String>[];
  for (final file in p.test) {
    if (file.path == 'test/architecture_test.dart') continue;
    final dir = file.path.substring(0, file.path.lastIndexOf('/'));
    if (dir == 'test') {
      out.add(
        '${file.path}: only architecture_test.dart sits at the test root',
      );
    } else if (!libDirs.contains('lib${dir.substring('test'.length)}')) {
      out.add(
        '${file.path}: lib${dir.substring('test'.length)}/ does not exist',
      );
    }
  }
  return out;
}

/// No `Map<String, dynamic>` in domain files (CLAUDE §1.2).
List<String> typedDomainRule(Project p) => [
  for (final file in p.handWritten)
    if (_tryClassify(file.path)?.layer == 'domain' &&
        RegExp(r'Map<\s*String\s*,\s*dynamic\s*>').hasMatch(file.content))
      '${file.path}: Map<String, dynamic> may not cross the domain boundary',
];

/// Riverpod is the only DI and state tool (CLAUDE §2).
List<String> stateManagementRule(Project p) {
  final banned = RegExp(
    r'\b(StateNotifier|StateNotifierProvider|StateProvider|ChangeNotifierProvider|GetIt)\b|package:get_it/',
  );
  return [
    for (final file in p.handWritten)
      if (banned.firstMatch(file.content) case final m?)
        '${file.path}: ${m.group(0)} — use Notifier/AsyncNotifier and Riverpod DI',
  ];
}

const Map<String, Rule> rules = {
  'placement': placementRule,
  'layers': layerRule,
  'cross-module': crossModuleRule,
  'public API files': publicApiRule,
  'import graph': graphRule,
  'package imports': packageImportsRule,
  'test mirror': testMirrorRule,
  'typed domain': typedDomainRule,
  'state management': stateManagementRule,
};

