const _package = 'expense_tracker';
const _layers = {'domain', 'data', 'presentation'};
const _apiKinds = {'routes', 'domain', 'data', 'presentation'};
const _layerFolders = {
  'domain': {'entities', 'repositories', 'usecases'},
  'data': {'models', 'datasources', 'repositories'},
  'presentation': {'pages', 'widgets', 'providers'},
};
const _appRootFiles = {'lib/main.dart', 'lib/app.dart'};
const _router = 'lib/core/router/app_router.dart';

class SourceFile {
  const SourceFile(this.path, this.content);

  /// Project-relative path with forward slashes, e.g. `lib/core/x.dart`.
  final String path;
  final String content;
}

class Project {
  Project(this.lib, this.test);

  /// Builds a project from `{path: content}`; paths starting with `lib/` or
  /// `test/` are sorted into the matching list.
  factory Project.of(Map<String, String> files) => Project(
    [
      for (final e in files.entries)
        if (e.key.startsWith('lib/')) SourceFile(e.key, e.value),
    ],
    [
      for (final e in files.entries)
        if (e.key.startsWith('test/')) SourceFile(e.key, e.value),
    ],
  );

  factory Project.fromDisk() {
    List<SourceFile> scan(String root) => [
      for (final entity in Directory(root).listSync(recursive: true))
        if (entity is File && entity.path.endsWith('.dart'))
          SourceFile(
            entity.path.replaceAll(r'\', '/'),
            entity.readAsStringSync(),
          ),
    ];
    return Project(scan('lib'), scan('test'));
  }

  final List<SourceFile> lib;
  final List<SourceFile> test;

  late final Set<String> libPaths = {for (final f in lib) f.path};

  /// Hand-written lib files (generated code is not held to the import rules).
  Iterable<SourceFile> get handWritten => lib.where((f) => !isGeneratedFile(f));
}

bool isGenerated(String path) =>
    path.endsWith('.g.dart') ||
    path.endsWith('.freezed.dart') ||
    path.startsWith('lib/core/l10n/generated/');

/// Generated by path, or by a tool header (e.g. drift_dev's migration test
/// helpers). Generated code is not held to the import rules.
bool isGeneratedFile(SourceFile file) =>
    isGenerated(file.path) ||
    RegExp(
      r'^// GENERATED (BY|CODE)',
      multiLine: true,
    ).hasMatch(file.content.substring(0, file.content.length.clamp(0, 400)));

/// Where a lib file sits in the architecture.
class Loc {
  const Loc.appRoot() : this._(Area.appRoot);
  const Loc.core() : this._(Area.core);
  const Loc.api(String module, String api)
    : this._(Area.feature, module: module, api: api);
  const Loc._(this.area, {this.module, this.api})
    : slice = null,
      layer = null,
      inner = const [],
      singleSlice = false;
  const Loc.layer(
    String this.module,
    String this.slice,
    String this.layer,
    this.inner, {
    required this.singleSlice,
  }) : area = Area.feature,
       api = null;

  final Area area;
  final String? module;
  final String? slice;
  final String? layer;

  /// For a module root file: `routes`, `domain`, `data` or `presentation`.
  final String? api;

  /// Path segments below the layer folder.
  final List<String> inner;
  final bool singleSlice;

  bool get isApi => api != null;
  bool get isShared => slice == 'shared' && !singleSlice;

  /// The layer whose import rules apply. Routes files compose pages, so they
  /// follow presentation rules.
  String? get effectiveLayer => api == 'routes' ? 'presentation' : layer;

  /// `data/<slice>_providers.dart`, the only data file presentation may use.
  bool get isWiring =>
      layer == 'data' &&
      inner.length == 1 &&
      inner.single == '${slice}_providers.dart';
}

enum Area { appRoot, core, feature }

/// Classifies [path] (under `lib/`); returns a [Loc] or throws a
/// [FormatException] explaining why the file is misplaced.
Loc classify(String path) {
  if (_appRootFiles.contains(path)) return const Loc.appRoot();
  final seg = path.split('/');
  if (seg.length > 2 && seg[1] == 'core') return const Loc.core();
  if (seg.length < 4 || seg[1] != 'features') {
    throw const FormatException(
      'must be under lib/core/ or lib/features/<module>/',
    );
  }
  final module = seg[2];
  final rest = seg.sublist(3);
  if (rest.length == 1) {
    final base = _stripGenerated(rest.single);
    for (final kind in _apiKinds) {
      if (base == '${module}_$kind.dart') return Loc.api(module, kind);
    }
    throw FormatException(
      'only ${module}_{routes,domain,data,presentation}.dart may sit at the module root',
    );
  }
  final singleSlice = _layers.contains(rest[0]);
  final slice = singleSlice ? module : rest[0];
  final layerIndex = singleSlice ? 0 : 1;
  if (rest.length < layerIndex + 2 || !_layers.contains(rest[layerIndex])) {
    throw const FormatException(
      'a slice folder must contain only domain/, data/ and presentation/',
    );
  }
  final layer = rest[layerIndex];
  final inner = rest.sublist(layerIndex + 1);
  final loc = Loc.layer(module, slice, layer, inner, singleSlice: singleSlice);
  if (inner.length == 1) {
    if (layer == 'data' &&
        _stripGenerated(inner.single) == '${slice}_providers.dart') {
      return loc;
    }
    throw FormatException(
      layer == 'data'
          ? 'only ${slice}_providers.dart may sit directly in data/'
          : 'files in $layer/ go in ${_layerFolders[layer]!.join('/, ')}/',
    );
  }
  if (!_layerFolders[layer]!.contains(inner.first)) {
    throw FormatException(
      '$layer/ may only contain ${_layerFolders[layer]!.join('/, ')}/',
    );
  }
  return loc;
}

String _stripGenerated(String name) =>
    name.replaceFirst(RegExp(r'\.(g|freezed)\.dart$'), '.dart');

class Directive {
  const Directive(this.keyword, this.uri);

  final String keyword;
  final String uri;

  bool get isRelative =>
      !uri.startsWith('dart:') && !uri.startsWith('package:');

  /// The lib path of a project import, or null for anything else.
  String? get target => uri.startsWith('package:$_package/')
      ? 'lib/${uri.substring('package:$_package/'.length)}'
      : null;

  @override
  String toString() => "$keyword '$uri'";
}

final _directivePattern = RegExp(
  r'''^\s*(import|export)\s+['"]([^'"]+)['"]''',
  multiLine: true,
);

List<Directive> directivesOf(String content) => [
  for (final m in _directivePattern.allMatches(content))
    Directive(m.group(1)!, m.group(2)!),
];

Loc? _tryClassify(String path) {
  try {
    return classify(path);
  } on FormatException {
    return null;
  }
}

